import 'dart:convert';

import 'package:http/http.dart' as http;

import '../models/diet_models.dart';
import 'api_key_service.dart';
import 'gemini_service.dart' show GeminiException;

/// Gemini-backed food analyser used by the Validate button in the Diet
/// section. Uses the active key/endpoint validated in the Keys page.
class DietService {
  static Future<FoodAnalysis> analyzeFood({
    required String foodItem,
    required String foodType,
    required String quantity,
    String? photoName,
  }) async {
    final config = await ApiKeyStore.instance.requireActiveConfig();

    final prompt =
        '''
You are an expert registered dietitian and food scientist.
Estimate the nutrition for the following food portion.

FOOD ITEM: $foodItem
FOOD TYPE: $foodType
QUANTITY: $quantity
PHOTO ATTACHED: ${photoName == null || photoName.isEmpty ? 'No' : 'Yes ($photoName) - use it only as extra context, do not invent details not present'}

Return ONLY a valid JSON object (no markdown, no code fences, no explanation):
{
  "calories": 350,
  "nutrients": [
    {"name": "Protein", "amount": "12 g"},
    {"name": "Carbohydrates", "amount": "45 g"},
    {"name": "Fat", "amount": "10 g"},
    {"name": "Fibre", "amount": "4 g"}
  ],
  "summary": "2 short sentences describing the main nutrients and any caveat."
}

RULES:
- calories must be a single integer for the exact quantity given.
- Include 3 to 6 key nutrients with realistic amounts for that quantity.
- Respect the food type (veg / non veg) when estimating protein and fat sources.
- Be honest that values are estimates; keep the summary short.
- Strictly valid JSON, no trailing commas.
''';

    final requestBody = {
      'contents': [
        {
          'parts': [
            {'text': prompt},
          ],
        },
      ],
      'generationConfig': {
        'temperature': 0.4,
        'topK': 40,
        'topP': 0.95,
        'maxOutputTokens': 1024,
      },
    };

    final uri = Uri.parse(config.generateUrl);
    late final http.Response response;
    try {
      response = await http
          .post(
            uri,
            headers: geminiHeaders(config.key),
            body: jsonEncode(requestBody),
          )
          .timeout(const Duration(seconds: 60));
    } on Exception catch (e) {
      throw GeminiException('Could not reach Gemini: $e');
    }

    if (response.statusCode != 200) {
      Object? errorBody;
      try {
        errorBody = jsonDecode(response.body);
      } catch (_) {
        errorBody = null;
      }
      final message = errorBody is Map<String, dynamic>
          ? (errorBody['error']?['message'] ?? 'Unknown error from Gemini API')
          : 'Unknown error from Gemini API';
      throw GeminiException('API Error ${response.statusCode}: $message');
    }

    final data = jsonDecode(response.body) as Map<String, dynamic>;
    final candidates = data['candidates'] as List<dynamic>?;
    if (candidates == null || candidates.isEmpty) {
      throw const GeminiException('No response generated by Gemini.');
    }
    final parts =
        (candidates[0]['content'] as Map<String, dynamic>?)?['parts']
            as List<dynamic>?;
    if (parts == null || parts.isEmpty) {
      throw const GeminiException('Empty content in Gemini response.');
    }

    var text = (parts[0]['text'] as String? ?? '').trim();
    if (text.startsWith('```')) {
      text = text.replaceFirst(RegExp(r'^```[a-z]*\n?'), '');
      text = text.replaceFirst(RegExp(r'\n?```$'), '');
      text = text.trim();
    }

    Map<String, dynamic> parsed;
    try {
      parsed = jsonDecode(text) as Map<String, dynamic>;
    } catch (_) {
      throw const GeminiException(
        'Could not parse the food analysis from Gemini. Please try again.',
      );
    }

    final nutrients = (parsed['nutrients'] as List<dynamic>? ?? [])
        .whereType<Map<String, dynamic>>()
        .map(
          (item) => FoodNutrient(
            name: (item['name'] as String?)?.trim().isNotEmpty == true
                ? item['name'] as String
                : 'Nutrient',
            amount: (item['amount'] as String?) ?? '-',
          ),
        )
        .toList();

    return FoodAnalysis(
      foodItem: foodItem.trim(),
      foodType: foodType,
      quantity: quantity.trim(),
      calories: _asInt(parsed['calories'], fallback: 0),
      nutrients: nutrients,
      summary: (parsed['summary'] as String?) ?? '',
      analysedAt: DateTime.now(),
    );
  }

  static int _asInt(dynamic value, {required int fallback}) {
    if (value is int) return value;
    if (value is double) return value.round();
    if (value is String) return int.tryParse(value) ?? fallback;
    return fallback;
  }
}
