import 'dart:convert';

import 'package:http/http.dart' as http;

import '../models/workout_models.dart';
import 'youtube_service.dart';

class GeminiService {
  static const String _apiKey =
      String.fromEnvironment('GEMINI_API_KEY', defaultValue: '');
  static const String _apiUrl =
      'https://generativelanguage.googleapis.com/v1beta/models/gemini-3.1-flash-lite:generateContent';

  /// Calls the Gemini API and returns a [WorkoutModel] with AI-generated exercises.
  static Future<WorkoutModel> generateWorkout({
    required String name,
    required List<String> muscles,
    required String duration,
    required String difficulty,
    required String equipment,
  }) async {
    if (_apiKey.isEmpty) {
      throw const GeminiException(
        'GEMINI_API_KEY is not configured. Run with '
        '--dart-define-from-file=env.json or '
        '--dart-define=GEMINI_API_KEY=...',
      );
    }

    final focusStr = muscles.isEmpty ? 'Full Body' : muscles.join(' & ');

    final prompt =
        '''
You are an expert certified personal trainer and sports scientist.
Generate a detailed, safe, and science-backed workout plan based on the user's inputs below.

WORKOUT PARAMETERS:
- Routine Name: $name
- Target Muscles: ${muscles.join(', ')}
- Duration: $duration
- Difficulty Level: $difficulty
- Equipment Available: $equipment

INSTRUCTIONS:
Return ONLY a valid JSON object (no markdown, no code fences, no explanation) with this exact structure:
{
  "exercises": [
    {
      "name": "Exercise Name",
      "category": "Muscle Group",
      "difficulty": "$difficulty",
      "target": "Primary muscles targeted • Equipment used",
      "equipment": "Equipment name",
      "sets": "X sets",
      "reps": "X-X reps",
      "rest": "Xs",
      "pr": "Suggested starting weight or Bodyweight",
      "videoUrl": "https://www.youtube.com/results?search_query=...",
      "cues": [
        "Detailed coaching cue 1 for proper form.",
        "Detailed coaching cue 2 for safety.",
        "Detailed coaching cue 3 for performance."
      ]
    }
  ]
}

RULES:
- Include 4 to 6 exercises appropriate for the target muscles and difficulty.
- Each exercise must have exactly 3 coaching cues that are detailed and actionable.
- Match exercise selection to the available equipment: $equipment.
- Respect the difficulty level ($difficulty): Beginner uses lighter loads and simpler movements; Advanced uses compound lifts and higher RPE.
- Ensure exercises fit within the $duration timeframe.
- The JSON must be strictly valid — no trailing commas, no comments.
''';

    final requestBody = {
      'contents': [
        {
          'parts': [
            {'text': prompt},
          ],
        },
      ],
      'generationConfig': {
        'temperature': 0.7,
        'topK': 40,
        'topP': 0.95,
        'maxOutputTokens': 2048,
      },
    };

    final uri = Uri.parse('$_apiUrl?key=$_apiKey');

    final response = await http.post(
      uri,
      headers: {'Content-Type': 'application/json'},
      body: jsonEncode(requestBody),
    );

    if (response.statusCode != 200) {
      final errorBody = jsonDecode(response.body);
      final errorMessage =
          errorBody['error']?['message'] ?? 'Unknown error from Gemini API';
      throw GeminiException('API Error ${response.statusCode}: $errorMessage');
    }

    final responseData = jsonDecode(response.body) as Map<String, dynamic>;

    // Extract the text content from the Gemini response
    final candidates = responseData['candidates'] as List<dynamic>?;
    if (candidates == null || candidates.isEmpty) {
      throw const GeminiException('No response generated by Gemini.');
    }

    final content = candidates[0]['content'] as Map<String, dynamic>?;
    final parts = content?['parts'] as List<dynamic>?;
    if (parts == null || parts.isEmpty) {
      throw const GeminiException('Empty content in Gemini response.');
    }

    String rawText = parts[0]['text'] as String? ?? '';

    // Strip any accidental markdown code fences the model might add
    rawText = rawText.trim();
    if (rawText.startsWith('```')) {
      rawText = rawText.replaceFirst(RegExp(r'^```[a-z]*\n?'), '');
      rawText = rawText.replaceFirst(RegExp(r'\n?```$'), '');
      rawText = rawText.trim();
    }

    Map<String, dynamic> parsed;
    try {
      parsed = jsonDecode(rawText) as Map<String, dynamic>;
    } catch (_) {
      throw const GeminiException(
        'Could not parse the workout plan from Gemini. Please try again.',
      );
    }

    final exercisesJson = parsed['exercises'] as List<dynamic>?;
    if (exercisesJson == null || exercisesJson.isEmpty) {
      throw const GeminiException(
        'Gemini returned an empty exercise list. Please try again.',
      );
    }

    final exercises = await Future.wait(
      exercisesJson.map((e) async {
        final ex = e as Map<String, dynamic>;
        final cuesRaw = ex['cues'] as List<dynamic>? ?? [];
        final exerciseName = (ex['name'] as String?) ?? 'Unknown Exercise';

        // Obtain exact matching video demonstration for this exercise
        String? resolvedVideo = ex['videoUrl'] as String?;
        if (resolvedVideo == null ||
            resolvedVideo.isEmpty ||
            resolvedVideo.contains('search_query')) {
          resolvedVideo = await YouTubeService.getExactVideoUrl(exerciseName);
        }

        return ExerciseModel(
          name: exerciseName,
          category: (ex['category'] as String?) ?? focusStr,
          difficulty: (ex['difficulty'] as String?) ?? difficulty,
          target: (ex['target'] as String?) ?? focusStr,
          equipment: (ex['equipment'] as String?) ?? equipment,
          sets: (ex['sets'] as String?) ?? '3 sets',
          reps: (ex['reps'] as String?) ?? '10 reps',
          rest: (ex['rest'] as String?) ?? '60s',
          pr: (ex['pr'] as String?) ?? 'Start light',
          videoUrl: resolvedVideo,
          cues: cuesRaw.map((c) => c.toString()).toList(),
        );
      }),
    );

    return WorkoutModel(
      id: 'w-${DateTime.now().millisecondsSinceEpoch}',
      name: name.trim().isEmpty ? 'AI $focusStr Blast' : name.trim(),
      focus: focusStr,
      duration: duration,
      difficulty: difficulty,
      date: 'AI Generated',
      exercises: exercises,
    );
  }
}

/// Typed exception for Gemini API errors.
class GeminiException implements Exception {
  final String message;
  const GeminiException(this.message);

  @override
  String toString() => message;
}
